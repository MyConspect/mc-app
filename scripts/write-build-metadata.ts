import fs from "node:fs";
import path from "node:path";
import { loadEnvConfig } from "@next/env";
import { siteLastUpdatedIsoLive } from "../lib/siteLastUpdatedLive";

loadEnvConfig(process.cwd());

const OUT = path.join(
  process.cwd(),
  "lib",
  "build",
  "siteLastUpdated.generated.ts",
);

const iso = siteLastUpdatedIsoLive();
const body = `/** @generated by scripts/write-build-metadata.ts — do not edit */
export const BUILD_SITE_LAST_UPDATED_ISO = ${JSON.stringify(iso)} as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, "utf8");
console.log(`build-metadata: SITE_LAST_UPDATED=${iso}`);
